"""可复用的手绘人物和道具。每个函数返回笔画列表（每条笔画是一串点）。

人物都没有五官——组织人是可以互换的。坐标以脚底（或桌面）为原点，
s 为缩放，flip=True 时左右镜像（面朝左）。
"""
import math

from engine import circle, ellipse, rect


def _tf(x, y, s, flip):
    k = -1 if flip else 1

    def P(*pts):
        return [(x + k * px * s, y + py * s) for px, py in pts]
    return P


