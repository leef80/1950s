def alarm_clock(cx, cy, r=24, hour=6.5):
    hx = math.sin(math.radians(hour * 30))
    hy = -math.cos(math.radians(hour * 30))
    mins = (hour % 1) * 360
    mx, my = math.sin(math.radians(mins)), -math.cos(math.radians(mins))
    return [
        circle(cx, cy, r),
        ellipse(cx - r * 0.7, cy - r * 0.95, 9, 7, 180, 360),
        ellipse(cx + r * 0.7, cy - r * 0.95, 9, 7, 180, 360),
        [(cx, cy), (cx + hx * r * 0.5, cy + hy * r * 0.5)],
        [(cx, cy), (cx + mx * r * 0.8, cy + my * r * 0.8)],
        [(cx - r * 0.6, cy + r * 0.8), (cx - r * 0.85, cy + r * 1.2)],
        [(cx + r * 0.6, cy + r * 0.8), (cx + r * 0.85, cy + r * 1.2)],
    ]


